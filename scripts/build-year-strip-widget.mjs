import { build } from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { writeFileSync } from "node:fs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const result = await build({
  entryPoints: [join(root, "widgets", "year-strip", "entry.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: true,
  write: false,
});

const javascript = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>html,body{margin:0;padding:0}body{box-sizing:border-box;padding:12px;background:var(--color-background-primary,#fff)}*{box-sizing:border-box}#app{width:100%}</style></head><body><div id="app" aria-live="polite"></div><script>${javascript}</script></body></html>`;
const generated = `// Generated by scripts/build-year-strip-widget.mjs. Do not edit.\nexport const YEAR_STRIP_WIDGET_HTML = ${JSON.stringify(html)};\n`;
writeFileSync(join(root, "widgets", "year-strip", "generated.ts"), generated, "utf8");
console.log(`[build-widget] year-strip generated (${Buffer.byteLength(html)} bytes)`);
